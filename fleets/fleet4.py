def _slope_from_name(name: str) -> tuple[int, int]:
    """Heuristically extract dominant slope -p/q from operator name like 's1o3'.
    Returns (p, q) with gcd(p,q)=1, or (1, 2) as a default."""
    import re
    m = re.search(r"s(\d+)o(\d+)", name)
    if m:
        p = int(m.group(1))
        q = int(m.group(2))
        g = math.gcd(p, q)
        return p // g, q // g
    # Multi-edge: take dominant edge (the last one)
    m = re.search(r"(\d+)o(\d+)_then", name)
    if m:
        # left edge -- not dominant
        pass
    m_all = re.findall(r"(\d+)o(\d+)", name)
    if m_all:
        # dominant is the more negative slope -- in our naming, the rightmost in MULTI
        p, q = int(m_all[-1][0]), int(m_all[-1][1])
        g = math.gcd(p, q)
        return p // g, q // g
    return 1, 2


def compute_anti_stokes_skeleton(roots: list[tuple[float, float]],
                                  p: int, q: int,
                                  tol: float = 1e-7) -> dict[str, Any]:
    """
    Compute the anti-Stokes skeleton on the ramified cover t-plane for the
    irregular type Q_i(t) = c_i t^p + (lower, ignored here).

    For each ordered pair (i, j), the anti-Stokes directions are
        phi in [0, 2 pi) : Re((c_i - c_j) e^{i p phi}) = 0
    giving 2 p directions per pair (when Delta_{ij} != 0).
    """
    N = len(roots)
    cs = [complex(re, im) for (re, im) in roots]
    rays_per_pair: list[dict[str, Any]] = []
    all_phis: list[float] = []
    for i in range(N):
        for j in range(i + 1, N):
            d = cs[i] - cs[j]
            if abs(d) < tol:
                # collinear / equal -- no anti-Stokes direction (degenerate)
                rays_per_pair.append({
                    "pair": [i, j],
                    "delta": [d.real, d.imag],
                    "delta_zero": True,
                    "phis": [],
                })
                continue
            arg_d = math.atan2(d.imag, d.real)
            # phi such that arg(d) + p phi == pi/2 (mod pi)
            # => phi = (pi/2 - arg(d) + k pi) / p, k = 0, 1, ..., 2p - 1
            phis = []
            for k in range(2 * p):
                phi = (math.pi / 2 - arg_d + k * math.pi) / p
                phi = phi % (2 * math.pi)
                phis.append(phi)
            phis.sort()
            rays_per_pair.append({
                "pair": [i, j],
                "delta": [d.real, d.imag],
                "delta_zero": False,
                "phis": phis,
            })
            all_phis.extend(phis)

    # Cluster all phi values; tolerance scales with expected ray density.
    # Expected total rays = 2 p * N(N-1)/2; expected angular gap = 2pi / expected_total.
    # Use eps = expected_gap / 8 so that genuine coincidences (multiplicity > 1) are
    # caught while distinct rays at the natural spacing are not merged.
    expected_total = max(1, 2 * p * (N * (N - 1) // 2))
    eps_density = 2 * math.pi / (expected_total * 8.0) if expected_total > 0 else 1e-4
    eps = min(2 * math.pi / (50.0 * p) if p > 0 else 1e-3, eps_density)
    all_phis_sorted = sorted(all_phis)
    clusters: list[list[float]] = []
    for phi in all_phis_sorted:
        if clusters and abs(phi - clusters[-1][-1]) < eps:
            clusters[-1].append(phi)
        else:
            clusters.append([phi])
    # Merge wrap-around (last cluster near 2pi and first cluster near 0)
    if len(clusters) >= 2 and abs((clusters[0][0] + 2 * math.pi) - clusters[-1][-1]) < eps:
        clusters[0] = clusters[-1] + clusters[0]
        clusters.pop()

    distinct_rays = [{"phi_mean": sum(c) / len(c), "multiplicity": len(c)} for c in clusters]
    distinct_rays.sort(key=lambda r: r["phi_mean"])

    # Compute the multiplicity profile (multiplicities sorted descending)
    mult_profile = sorted([r["multiplicity"] for r in distinct_rays], reverse=True)

    # Dominance order: in each sector (between consecutive distinct rays),
    # compute the order of Re(c_i e^{i p phi}) for a representative phi.
    sectors: list[dict[str, Any]] = []
    if len(distinct_rays) >= 2:
        for s in range(len(distinct_rays)):
            phi_a = distinct_rays[s]["phi_mean"]
            phi_b = distinct_rays[(s + 1) % len(distinct_rays)]["phi_mean"]
            # representative interior
            if phi_b > phi_a:
                phi_mid = (phi_a + phi_b) / 2
            else:
                phi_mid = (phi_a + phi_b + 2 * math.pi) / 2
                phi_mid = phi_mid % (2 * math.pi)
            # Compute Re(c_i e^{i p phi_mid}) for each i
            values = [(i, (cs[i] * cmath.exp(1j * p * phi_mid)).real) for i in range(N)]
            values.sort(key=lambda v: -v[1])  # descending
            dominance = [v[0] for v in values]
            sectors.append({
                "between_rays": [s, (s + 1) % len(distinct_rays)],
                "phi_representative": phi_mid,
                "dominance_order": dominance,
            })

    return {
        "p": p,
        "q": q,
        "N": N,
        "n_pairs": N * (N - 1) // 2,
        "rays_per_pair_count": [len(r["phis"]) for r in rays_per_pair],
        "n_distinct_rays_cover": len(distinct_rays),
        "ray_multiplicity_profile_cover": mult_profile,
        "n_sectors_cover": len(distinct_rays) if len(distinct_rays) > 0 else 1,
        "delta_zero_pair_count": sum(1 for r in rays_per_pair if r["delta_zero"]),
        # base-plane (x-plane) projection: identify phi ~ phi + 2 pi / q
        # number of distinct rays mod (2 pi / q):
        "n_distinct_rays_base": _project_to_base(distinct_rays, q),
        "rays_per_pair": rays_per_pair,
        "distinct_rays_cover": distinct_rays,
        "sectors_sample": sectors[:8],  # store at most 8 sectors per op for brevity
    }


def _project_to_base(distinct_rays: list[dict[str, float]], q: int) -> int:
    """Identify rays modulo 2 pi / q to count distinct x-plane Stokes directions."""
    if q <= 1 or not distinct_rays:
        return len(distinct_rays)
    period = 2 * math.pi / q
    # Use a tight tolerance: relative to the typical ray spacing.
    n = len(distinct_rays)
    eps = min(period / max(50, 10 * n), 1e-4)
    folded = sorted([(r["phi_mean"] % period) for r in distinct_rays])
    distinct: list[float] = []
    for v in folded:
        if not distinct or abs(v - distinct[-1]) > eps:
            distinct.append(v)
    if len(distinct) >= 2 and (distinct[0] + period - distinct[-1]) < eps:
        distinct.pop()
    return len(distinct)


