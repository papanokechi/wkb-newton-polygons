def stratified_sample(invariants: list[dict[str, Any]], n_per_class: int = 2) -> list[dict[str, Any]]:
    """Pick 20 representative operators across the Phase-III taxonomy."""
    buckets: dict[str, list[dict[str, Any]]] = {
        "HIGHQ_simple_singleedge": [],
        "HIGHQ_genc_singleedge": [],
        "MULTI": [],
        "MULTI3": [],
        "SYS": [],
        "MIX": [],
        "CTRL_disc": [],
        "CTRL_zeroroot": [],
        "CTRL_conjroots": [],
        "NEST": [],
        "GAL": [],
        "OMEGA": [],
        "PINV": [],
    }
    for inv in invariants:
        name = inv["operator"]
        if name.startswith("HIGHQ_simple") and inv["n_edges"] == 1:
            buckets["HIGHQ_simple_singleedge"].append(inv)
        elif name.startswith("HIGHQ_genc") and inv["n_edges"] == 1:
            buckets["HIGHQ_genc_singleedge"].append(inv)
        elif name.startswith("MULTI3"):
            buckets["MULTI3"].append(inv)
        elif name.startswith("MULTI"):
            buckets["MULTI"].append(inv)
        elif name.startswith("SYS"):
            buckets["SYS"].append(inv)
        elif name.startswith("MIX"):
            buckets["MIX"].append(inv)
        elif name.startswith("CTRL_disc"):
            buckets["CTRL_disc"].append(inv)
        elif name.startswith("CTRL_zeroroot"):
            buckets["CTRL_zeroroot"].append(inv)
        elif name.startswith("CTRL_conjroots"):
            buckets["CTRL_conjroots"].append(inv)
        elif name.startswith("NEST"):
            buckets["NEST"].append(inv)
        elif name.startswith("GAL"):
            buckets["GAL"].append(inv)
        elif name.startswith("OMEGA"):
            buckets["OMEGA"].append(inv)
        elif name.startswith("PINV"):
            buckets["PINV"].append(inv)

    sample: list[dict[str, Any]] = []
    for bname, lst in buckets.items():
        sample.extend(lst[: max(1, n_per_class)])
    # Truncate to 20 by trimming the largest buckets first
    while len(sample) > 20:
        # remove last entry from largest bucket
        bigb = max(buckets.values(), key=lambda L: sum(1 for x in L if x in sample))
        for x in reversed(bigb):
            if x in sample:
                sample.remove(x)
                break
    return sample


