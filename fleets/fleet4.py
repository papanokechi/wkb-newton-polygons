def main() -> None:
    print("[Phase IV] analytic_reader: building classical framework summary...")
    framework = ANALYTIC_FRAMEWORK
    print(f"[Phase IV] analytic_reader: {len(framework)} top-level entries.")

    print("[Phase IV] invariant_lifter: building lifting table...")
    lift_table = LIFT_TABLE
    print(f"[Phase IV] invariant_lifter: {len(lift_table)} invariant rows.")

    print("[Phase IV] operator_sampler: loading Phase-III invariants...")
    invariants = load_phase3_invariants()
    print(f"[Phase IV] operator_sampler: {len(invariants)} operators loaded from Phase III.")
    sample = stratified_sample(invariants)
    print(f"[Phase IV] operator_sampler: stratified sample size = {len(sample)}.")

    print("[Phase IV] stokes_engine: computing anti-Stokes skeleton for ALL 48 ops...")
    stokes_data: dict[str, dict[str, Any]] = {}
    for inv in invariants:
        roots = inv.get("full_constellation", [])
        if not roots:
            continue
        p, q = _slope_from_name(inv["operator"])
        # Filter to finite, real-valued roots (skip systems with degenerate constellation)
        roots = [(r[0], r[1]) for r in roots if abs(r[0]) < 1e9 and abs(r[1]) < 1e9]
        if len(roots) < 2:
            continue
        try:
            sk = compute_anti_stokes_skeleton(roots, p, q)
        except Exception as e:
            sk = {"p": p, "q": q, "N": len(roots), "error": str(e)}
        stokes_data[inv["operator"]] = sk
    print(f"[Phase IV] stokes_engine: anti-Stokes skeleton computed for {len(stokes_data)} ops.")

    print("[Phase IV] consistency_engine: cross-checking discrete vs analytic for sample...")
    consistency: list[dict[str, Any]] = []
    for inv in sample:
        sk = stokes_data.get(inv["operator"])
        if sk and "error" not in sk:
            consistency.append(check_consistency(inv, sk))
    print(f"[Phase IV] consistency_engine: {len(consistency)} consistency reports.")

    print("[Phase IV] theorem_engine: proposing analytic-lifting theorems...")
    theorems = propose_theorems(invariants, stokes_data, consistency)
    print(f"[Phase IV] theorem_engine: {len(theorems)} theorems proposed.")

    print("[Phase IV] writing outputs...")
    write_outputs(framework, lift_table, sample, stokes_data, consistency, theorems)
    write_report(framework, lift_table, sample, stokes_data, consistency, theorems, invariants)
    print("[Phase IV] DONE.")


if __name__ == "__main__":
    main()
