def check_consistency(inv: dict[str, Any], stokes: dict[str, Any]) -> dict[str, Any]:
    """Cross-check predictions for one operator."""
    p, q, N = stokes["p"], stokes["q"], stokes["N"]
    findings: list[str] = []

    # (1) Ray count on cover: should be at most 2 p * N(N-1)/2; collisions reduce.
    expected_max = 2 * p * stokes["n_pairs"]
    actual = sum(stokes["rays_per_pair_count"])
    findings.append(
        f"Total ray count on cover: actual={actual}, expected_max={expected_max}, "
        f"ratio={actual / expected_max:.3f}" if expected_max else "Total ray count: N=1, trivial."
    )

    # (2) C_q-symmetry of the constellation should impose 2 pi / q rotational symmetry on the cover ray set
    n_distinct = stokes["n_distinct_rays_cover"]
    if q >= 2 and n_distinct > 0:
        if n_distinct % q == 0:
            findings.append(f"C_q rotational symmetry: PRESENT (n_rays_cover={n_distinct} divisible by q={q}).")
        else:
            findings.append(f"C_q rotational symmetry: NOT exact (n_rays_cover={n_distinct} not divisible by q={q}); maybe degenerate.")

    # (3) omega-resonance: extra ray clustering at denom > q.
    # AT2 predicts max-multiplicity >= 2 (necessary condition).
    # Naive prediction m/q is sub-naive at leading order; we report the gap.
    omega = inv.get("omega_resonance", {})
    if omega.get("is_resonant"):
        m = omega.get("denom", 0)
        findings.append(
            f"omega-resonance denom={m}>q={q}: anti-Stokes ray cluster enhancement expected "
            f"(AT2 necessary: max_mult >= 2; naive m/q = {round(m/q,2) if q else 'NA'})."
        )
        mult_profile = stokes["ray_multiplicity_profile_cover"]
        max_mult = max(mult_profile) if mult_profile else 0
        naive_pred = m / q if (m and q) else 1
        if max_mult >= naive_pred - 1e-9:
            verdict = "MATCHES naive m/q"
        elif max_mult >= 2:
            verdict = "necessary condition met (max_mult>=2), naive m/q under-predicts"
        else:
            verdict = "no enhancement detected"
        findings.append(
            f"Observed max ray multiplicity: {max_mult}; naive m/q = {round(naive_pred,2)}; AT2 verdict: {verdict}."
        )

    # (4) Multi-edge slope filtration
    if inv["n_edges"] >= 2:
        findings.append(
            f"Multi-edge ({inv['n_edges']} edges): anti-Stokes rays from leading edge "
            f"only computed here; cross-edge contributions require leading-Q-difference analysis."
        )
        if inv.get("multi_edge", {}).get("zero_roots", 0) > 0:
            findings.append("Zero-roots on dominant edge present; some Delta_{ij} = 0; anti-Stokes pairs collapse.")

    # (5) Symmetry inflation
    sym = inv.get("symmetry", {})
    if sym.get("inflated"):
        n_obs = sym["n_observed"]
        findings.append(
            f"Symmetry inflation C_{n_obs} > C_{q}: predicts an additional automorphism of "
            f"the anti-Stokes skeleton (rotation by 2 pi / {n_obs} on cover)."
        )
        # Check whether the ray pattern has period 2pi/n_obs
        period = 2 * math.pi / n_obs
        rays = [r["phi_mean"] for r in stokes["distinct_rays_cover"]]
        if rays:
            shifted = sorted([(r + period) % (2 * math.pi) for r in rays])
            original = sorted(rays)
            match = (len(shifted) == len(original) and
                     all(abs(shifted[i] - original[i]) < 0.05 for i in range(len(shifted))))
            findings.append(f"Inflation observable on anti-Stokes pattern: {'YES' if match else 'NO'}.")

    # (6) Z-resonance (cross-ring) -> arithmetic locus, not Stokes structure
    if inv.get("z_resonance_nontrivial_count", 0) > 0:
        findings.append(
            f"Cross-ring Z-resonance ({inv['z_resonance_nontrivial_count']} relations): "
            f"defines a chi_w-stratum in the discrete part of MW(L); does not affect the "
            f"local anti-Stokes skeleton at this leading order."
        )

    # (7) Nested ramification
    if inv["operator"].startswith("NEST"):
        findings.append(
            "Nested ramification: actual irregular-type degree is p*q' where q' is "
            "the inner ramification; anti-Stokes ray count predicted to scale by q'."
        )

    return {
        "operator": inv["operator"],
        "p": p, "q": q, "N": N,
        "findings": findings,
    }


